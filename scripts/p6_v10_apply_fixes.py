LOG = []


def find_one(pred, tag):
    idx = [i for i, l in enumerate(lines) if pred(l)]
    if len(idx) != 1:
        print('!! FAIL [%s] 命中 %d 次（须为 1 次）' % (tag, len(idx)))
        sys.exit(1)
    return idx[0]


def replace_line(pred, new, tag):
    i = find_one(pred, tag)
    old = lines[i]
    lines[i] = new
    LOG.append(('replace_line', tag, i + 1, old[:90], new[:90]))


def swap_in_line(pred, pairs, tag):
    i = find_one(pred, tag)
    old = lines[i]
    s = old
    for a, b in pairs:
        n = s.count(a)
        if n != 1:
            print('!! FAIL [%s] 片段命中 %d 次: %r' % (tag, n, a[:60]))
            sys.exit(1)
        s = s.replace(a, b)
    lines[i] = s
    LOG.append(('swap_in_line', tag, i + 1, old[:90], s[:90]))


def insert_after(pred, newlines, tag, offset=1):
    i = find_one(pred, tag)
    for k, nl in enumerate(newlines):
        lines.insert(i + offset + k, nl)
    LOG.append(('insert_after', tag, i + 1, lines[i][:90], '\n'.join(newlines)[:200]))


def replace_block(start_pred, end_pred, newlines, tag):
    i = find_one(start_pred, tag + '-start')
    j = find_one(end_pred, tag + '-end')
    if j < i:
        print('!! FAIL [%s] 起止顺序颠倒' % tag)
        sys.exit(1)
    lines[i:j + 1] = newlines
    LOG.append(('replace_block', tag, i + 1, '（%d 行）' % (j - i + 1), '\n'.join(newlines)[:200]))


