def find_one(pred, tag):
    idx = [i for i, l in enumerate(lines) if pred(l)]
    if len(idx) != 1:
        print('  !! FAIL  %-44s  hits=%d' % (tag, len(idx)))
        sys.exit(1)
    return idx[0]


def replace_line(pred, new, tag):
    i = find_one(pred, tag)
    lines[i] = new
    log.append(('整行替换', tag))


def append_line(pred, add, tag, sep=''):
    i = find_one(pred, tag)
    lines[i] = lines[i].rstrip() + sep + add
    log.append(('行尾追加', tag))


def swap_in_line(pred, old, new, tag):
    i = find_one(pred, tag)
    if old not in lines[i]:
        print('  !! FAIL  %-44s  锚点缺失: %s' % (tag, old))
        sys.exit(1)
    lines[i] = lines[i].replace(old, new)
    log.append(('行内替换', tag))


def insert_after(pred, newlines, tag):
    i = find_one(pred, tag)
    for k, nl in enumerate(newlines):
        lines.insert(i + 1 + k, nl)
    log.append(('插入 %d 行' % len(newlines), tag))


