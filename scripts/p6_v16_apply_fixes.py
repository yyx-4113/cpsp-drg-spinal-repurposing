text = io.open(PIN, encoding='utf-8').read()


def rep(old, new, tag):
    global text
    n = text.count(old)
    if n != 1:
        print('!! FAIL [%s] 命中 %d 次（须为 1）' % (tag, n))
        sys.exit(1)
    text = text.replace(old, new)
    print('OK  [%s]' % tag)


def replace_row(prefix, new_row, tag):
    global text
    lines = text.split('\n')
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    if len(idx) != 1:
        print('!! FAIL [%s] 命中 %d 行（须为 1）' % (tag, len(idx)))
        sys.exit(1)
    lines[idx[0]] = new_row
    text = '\n'.join(lines)
    print('OK  [%s] 行 %d' % (tag, idx[0] + 1))


